var LANG_META = [
  { code: 'fr', label: 'Français',  dir: 'ltr' },
  { code: 'en', label: 'English',   dir: 'ltr' },
  { code: 'de', label: 'Deutsch',   dir: 'ltr' },
  { code: 'it', label: 'Italiano',  dir: 'ltr' },
  { code: 'zh', label: '中文',      dir: 'ltr' },
  { code: 'ja', label: '日本語',    dir: 'ltr' },
  { code: 'ar', label: 'العربية',   dir: 'rtl' },
  { code: 'ko', label: '한국어',    dir: 'ltr' },
  { code: 'pt', label: 'Português', dir: 'ltr' }
];

function applyLang(code) {
  var t = I18N[code];
  if (!t) return;
  var meta = LANG_META.find(function(l) { return l.code === code; });
  document.documentElement.lang = code;
  document.documentElement.dir = meta.dir;
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  var btn = document.getElementById('lang-btn-text');
  if (btn) btn.textContent = code.toUpperCase();
  if (t['page.title']) document.title = t['page.title'];
  // Mark active
  document.querySelectorAll('#lang-dropdown button').forEach(function(b) {
    b.classList.toggle('is-active', b.dataset.lang === code);
  });
  try { localStorage.setItem('lang', code); } catch(e) {}
}

document.addEventListener('DOMContentLoaded', function() {
  var toggle   = document.getElementById('lang-toggle');
  var dropdown = document.getElementById('lang-dropdown');
  var switcher = document.getElementById('lang-switcher');
  if (!toggle || !dropdown) return;

  LANG_META.forEach(function(lang) {
    var btn = document.createElement('button');
    btn.setAttribute('data-lang', lang.code);
    btn.textContent = lang.label;
    btn.addEventListener('click', function() {
      applyLang(lang.code);
      dropdown.classList.remove('is-open');
      toggle.setAttribute('aria-expanded', 'false');
    });
    dropdown.appendChild(btn);
  });

  toggle.addEventListener('click', function() {
    var open = dropdown.classList.toggle('is-open');
    toggle.setAttribute('aria-expanded', String(open));
  });
  document.addEventListener('click', function(e) {
    if (!switcher.contains(e.target)) {
      dropdown.classList.remove('is-open');
      toggle.setAttribute('aria-expanded', 'false');
    }
  });

  var saved = null;
  try { saved = localStorage.getItem('lang'); } catch(e) {}
  var nav2 = (navigator.language || '').substring(0, 2);
  var lang = (saved && I18N[saved]) ? saved : (I18N[nav2] ? nav2 : 'fr');
  applyLang(lang);
});
